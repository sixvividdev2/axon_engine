import { CaliberId } from './calibers';

export type ItemCategory =
  | 'weapon'
  | 'magazine'
  | 'ammo'
  | 'attachment'
  | 'medical'
  | 'gear'
  | 'food'
  | 'drink'
  | 'backpack';

export interface ItemSpec {
  id: string;
  name: string;
  shortName: string;
  category: ItemCategory;
  description: string;
  weightKg: number;
  gridW: number;
  gridH: number;
  stackable: boolean;
  maxStack: number;
  /** For magazines */
  magCapacity?: number;
  caliberId?: CaliberId;
  /** For medical items */
  healAmount?: number;
  stopsBleed?: boolean;
  curesLightBleed?: boolean;
  curesHeavyBleed?: boolean;
  curesFracture?: boolean;
  painkillerDurationSec?: number;
  /** For battery */
  batteryRestore?: number;
  /** For food & drink */
  hungerRestore?: number;
  thirstRestore?: number;
  staminaRestore?: number;
  /** For backpacks */
  backpackCols?: number;
  backpackRows?: number;
  /** For suppressors */
  suppressorType?: '9mm' | 'rifle';
  /** Linked weapon id if category === 'weapon' */
  weaponId?: string;
}

